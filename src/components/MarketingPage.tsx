import { jsPDF } from 'jspdf';
import JSZip from 'jszip';

export async function exportBrandPdf(brandName: string, palette: string[], tagline: string) {
  const doc = new jsPDF();
  doc.setFillColor(17, 19, 24);
  doc.rect(0, 0, 210, 297, 'F');
  doc.setTextColor(248, 248, 245);
  doc.setFontSize(22);
  doc.text(`${brandName} Brand Guidelines`, 18, 28);
  doc.setFontSize(12);
  doc.setTextColor(184, 243, 107);
  doc.text(tagline || 'Created with BrandForge', 18, 40);

  doc.setTextColor(248, 248, 245);
  doc.text('Primary palette', 18, 60);
  palette.slice(0, 5).forEach((hex, index) => {
    const x = 18 + (index % 3) * 58;
    const y = 74 + Math.floor(index / 3) * 28;
    doc.setFillColor(...hexToRgb(hex));
    doc.roundedRect(x, y, 42, 18, 3, 3, 'F');
    doc.setTextColor(17, 19, 24);
    doc.text(hex, x + 6, y + 13);
    doc.setTextColor(248, 248, 245);
  });

  doc.text('Brand principles', 18, 150);
  doc.text('• Stay minimal, confident, and memorable.', 18, 162);
  doc.text('• Use clear space and consistent spacing.', 18, 171);
  doc.text('• Keep typography deliberate and accessible.', 18, 180);

  doc.save(`${brandName.toLowerCase().replace(/\s+/g, '-')}-guidelines.pdf`);
}

export async function exportBrandZip(brandName: string, palette: string[], tagline: string) {
  const zip = new JSZip();
  const folder = zip.folder(`Brand-${brandName}`) as JSZip;

  folder.file('README.txt', `Brand: ${brandName}\nTagline: ${tagline}\nPalette: ${palette.join(', ')}`);
  folder.file('palette.json', JSON.stringify({ brandName, tagline, palette }, null, 2));
  folder.file('brand-summary.txt', `This package was generated by BrandForge in demo mode.\n`);

  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${brandName.toLowerCase().replace(/\s+/g, '-')}-brand-package.zip`;
  a.click();
  URL.revokeObjectURL(url);
}

function hexToRgb(hex: string) {
  const value = hex.replace('#', '');
  const num = Number.parseInt(value, 16);
  return [(num >> 16) & 255, (num >> 8) & 255, num & 255] as const;
}
